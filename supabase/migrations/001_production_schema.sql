create or replace function private.authorize_backend(p_secret text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  expected_hash text;
begin
  select value into expected_hash
  from private.app_config
  where key = 'backend_secret_hash';

  if coalesce(pg_catalog.encode(extensions.digest(p_secret, 'sha256'), 'hex'), '')
     <> coalesce(expected_hash, '') then
    raise exception 'Invalid backend credentials' using errcode = '42501';
  end if;
end;
$$;

create or replace function public.get_events()
returns table (id bigint, name text, description text, date date, "time" time without time zone, venue text, registration_count bigint)
language sql
security definer
set search_path = ''
as $$
  select e.id, e.name, e.description, e.date, e.time, e.venue, count(r.id)::bigint
  from public.events e
  left join public.registrations r on r.event_id = e.id
  group by e.id
  order by e.date, e.time;
$$;

create or replace function public.get_event(p_event_id bigint)
returns table (id bigint, name text, description text, date date, "time" time without time zone, venue text)
language sql
security definer
set search_path = ''
as $$
  select e.id, e.name, e.description, e.date, e.time, e.venue
  from public.events e where e.id = p_event_id;
$$;

create or replace function public.register_for_event(
  p_event_id bigint,
  p_full_name text,
  p_email text,
  p_phone text,
  p_admission_number text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.registrations (event_id, full_name, email, phone, admission_number)
  values (p_event_id, trim(p_full_name), lower(trim(p_email)), trim(p_phone), upper(trim(p_admission_number)));
end;
$$;

create or replace function public.admin_login(p_username text, p_password text)
returns boolean
language sql
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admins
    where username = trim(p_username)
      and password = extensions.crypt(p_password, password)
  );
$$;

create or replace function public.admin_create_event(
  p_secret text, p_name text, p_description text, p_date date, p_time time, p_venue text
)
returns setof public.events
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.authorize_backend(p_secret);
  return query
    insert into public.events (name, description, date, time, venue)
    values (trim(p_name), trim(p_description), p_date, p_time, trim(p_venue))
    returning *;
end;
$$;

create or replace function public.admin_update_event(
  p_secret text, p_event_id bigint, p_name text, p_description text,
  p_date date, p_time time, p_venue text
)
returns setof public.events
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.authorize_backend(p_secret);
  return query
    update public.events
    set name = trim(p_name), description = trim(p_description), date = p_date,
        time = p_time, venue = trim(p_venue)
    where id = p_event_id
    returning *;
end;
$$;

create or replace function public.admin_delete_event(p_secret text, p_event_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  deleted_id bigint;
begin
  perform private.authorize_backend(p_secret);
  delete from public.events where id = p_event_id returning id into deleted_id;
  return deleted_id is not null;
end;
$$;

create or replace function public.admin_registrations(p_secret text, p_event_id bigint)
returns table (id bigint, full_name text, email text, phone text, admission_number text, created_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.authorize_backend(p_secret);
  return query
    select r.id, r.full_name, r.email, r.phone, r.admission_number, r.created_at
    from public.registrations r
    where r.event_id = p_event_id
    order by r.created_at desc;
end;
$$;

