create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;

create table if not exists private.app_config (
  key text primary key,
  value text not null
);

revoke all on table private.app_config from public, anon, authenticated;

create table if not exists public.admins (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password text not null
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  description text not null check (char_length(description) between 1 and 1000),
  date date not null,
  time time without time zone not null,
  venue text not null check (char_length(venue) between 1 and 160)
);

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  full_name text not null check (char_length(full_name) between 1 and 120),
  email text not null check (
    char_length(email) between 3 and 254
    and email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ),
  phone text not null check (
    char_length(phone) between 7 and 20
    and phone ~ '^[+0-9][0-9 -]{6,19}$'
  ),
  admission_number text not null check (char_length(admission_number) between 1 and 50),
  created_at timestamptz not null default now(),
  unique (event_id, admission_number)
);

create index if not exists registrations_event_id_idx on public.registrations(event_id);

alter table public.admins enable row level security;
alter table public.events enable row level security;
alter table public.registrations enable row level security;

revoke all on table public.admins, public.events, public.registrations from anon, authenticated;

